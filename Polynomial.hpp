        template<typename U>
        Polynomial& powSelf(U n, U m = U(-1)) {
            auto frt = this->front(), inv = T(1) / frt;
            for (auto& i : *this) i *= inv;
            if (m == (U)(-1)) m = n;
            auto r = T(1);
            while (m) {
                if (m & 1) r *= frt;
                frt *= frt;
                m >>= 1;
            }
            return (this->lnSelf() *= T(n)).expSelf() *= r;
        }
